#!/usr/bin/env node
// Emits dist/vars.css: stable, meaningful CSS custom properties aliasing the
// StyleX-generated ones.
//
// WHY THIS EXISTS
// css.defineVars() names its variables `--<token>-<hash>` (`--bg-xqkwqtp`),
// where the hash is a build artefact — it changes if StyleX changes, if the
// defining file moves, or if its contents shift. So a consumer writing plain
// CSS has nothing durable to reference: `var(--bg-xqkwqtp)` works today and is
// not a contract, and inventing `var(--color-bg, #fff)` silently uses the
// fallback forever. Both failure modes have happened.
//
// This publishes the durable half: `--duro-color-bg` and friends, generated
// FROM the built tokens, so the mapping cannot drift from what StyleX actually
// emitted. Hand-maintaining it would just move the drift somewhere quieter.
//
// WHY THE SELECTOR INCLUDES [data-theme]
// A custom property's `var()` is substituted where the property is DECLARED,
// not where it is used. Declared only on :root, `--duro-color-bg` would compute
// once against the base (dark) palette and every descendant would inherit that
// computed colour — including subtrees a ThemeProvider has themed light.
// Re-declaring on the themed element makes it recompute there against the
// overridden values. ThemeProvider stamps data-theme for every theme, so that
// selector is exactly the set of scopes where the palette can change.

import {mkdir, writeFile} from 'node:fs/promises'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const distDir = join(here, '..', 'dist')

// Group name in the emitted variable. Singularised where the plural reads
// oddly on one value (`--duro-radii-sm` vs `--duro-radius-sm`).
const GROUP_NAMES = {
  colors: 'color',
  radii: 'radius',
  shadows: 'shadow',
  spacing: 'spacing',
  layoutSpacing: 'layout-spacing',
  typography: 'typography',
  typeScale: 'type-scale',
  duration: 'duration',
  easing: 'easing',
}

const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()

const tokens = await import(join(distDir, 'index.js'))
const raw = await import(join(distDir, 'raw.js'))

// The page canvas cannot use the aliases above. `body` sits ABOVE the element
// a theme lands on, so every var() it reads resolves against the base palette
// no matter what theme is applied below — which is why body has to be given
// the literal values per theme. Taken from raw.ts, the same source
// check-token-drift.mjs holds the .css.ts definitions to, so these cannot
// drift from the palette the components use.
//
// color-scheme is not a token — it is a browser hint for scrollbars, form
// controls and the caret — so which themes are "dark" is stated here.
const CANVAS = [
  {selector: 'body', palette: raw.darkColors, scheme: 'dark'},
  {selector: "body:has([data-theme='light'])", palette: raw.lightColors, scheme: 'light'},
  {
    selector: "body:has([data-theme='high-contrast'])",
    palette: raw.highContrastColors,
    scheme: 'dark',
  },
]

const canvas = CANVAS.map(
  ({selector, palette, scheme}) => `  ${selector} {
    background-color: ${palette.bg};
    color: ${palette.text};
    color-scheme: ${scheme};
  }`,
).join('\n\n')

const lines = []
let count = 0

for (const [group, alias] of Object.entries(GROUP_NAMES)) {
  const bag = tokens[group]
  if (!bag || typeof bag !== 'object') continue

  const entries = Object.entries(bag)
    // Only StyleX-backed values. A group may also hold plain constants
    // (breakpointsPx), which have no variable to alias.
    .filter(([, value]) => typeof value === 'string' && value.startsWith('var(--'))
    .sort(([a], [b]) => a.localeCompare(b))

  if (entries.length === 0) continue

  lines.push(`  /* ${group} */`)
  for (const [name, value] of entries) {
    lines.push(`  --duro-${alias}-${kebab(name)}: ${value};`)
    count++
  }
}

const css = `/*
 * GENERATED by scripts/generate-vars-css.mjs — do not edit.
 *
 * Stable public names for the design tokens. The StyleX variables these point
 * at carry a build-generated hash and are not a stable API; these are.
 *
 *   .thing { background: var(--duro-color-bg-card); }
 *
 * Declared on :root AND on every themed element, deliberately: a custom
 * property resolves its var() where it is declared, so a :root-only alias
 * would freeze the base palette and ignore the theme applied further down.
 */
:root,
[data-theme] {
${lines.join('\n')}
}

/*
 * The page canvas, per theme.
 *
 * In @layer reset so an app that paints its own body wins without needing
 * !important — unlayered author CSS beats layered CSS regardless of order.
 */
@layer reset {
${canvas}
}
`

await mkdir(distDir, {recursive: true})
await writeFile(join(distDir, 'vars.css'), css, 'utf8')
console.log(`generate-vars-css: ${count} public variables -> dist/vars.css`)
