#!/usr/bin/env node
/**
 * Generates src/components/Icon/phosphor-glyphs.ts from Phosphor's regular-weight SVGs.
 *
 *   node packages/ui/scripts/generate-phosphor-icons.mjs
 *
 * Input: src/components/Icon/phosphor-names.json, one Phosphor icon name per entry. It lists the
 * names Happier's React Native icon set uses that Duro does not define itself. A listed name
 * Duro also defines resolves to Duro's glyph (geometry.ts spreads these first).
 * Output: the geometry of each name as a `fill` glyph on Phosphor's own 256-unit viewBox. The
 * output is committed, so consumers do not need `@phosphor-icons/core`, which is a devDependency
 * of this package only. The script is idempotent: a second run changes nothing.
 *
 * A Happier name Phosphor spells differently is mapped in SOURCE_ALIASES below.
 */
import {readFileSync, writeFileSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {format, resolveConfig} from 'prettier'

const iconDirectory = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'components',
  'Icon',
)
const namesFile = join(iconDirectory, 'phosphor-names.json')
const outputFile = join(iconDirectory, 'phosphor-glyphs.ts')

const SOURCE_ALIASES = {
  'hard-drive-download': 'download-simple',
  'octagon-x': 'prohibit',
  'sidebar-left-close': 'sidebar',
  'sidebar-left-open': 'sidebar-simple',
}

const assetsDirectory = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'node_modules',
  '@phosphor-icons',
  'core',
  'assets',
  'regular',
)

function readShapes(name) {
  const sourceName = SOURCE_ALIASES[name] ?? name
  const svg = readFileSync(join(assetsDirectory, `${sourceName}.svg`), 'utf8')
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1]
  if (viewBox !== '0 0 256 256') {
    throw new Error(`${name}: expected the 256 viewBox, found ${viewBox}`)
  }
  const elements = [...svg.matchAll(/<(\w+)\s([^>]*?)\/>/g)]
  const shapes = elements.map(([, tag, attributes]) => {
    if (tag !== 'path') throw new Error(`${name}: unsupported <${tag}>`)
    return {tag, d: /\sd="([^"]+)"/.exec(` ${attributes}`)?.[1]}
  })
  if (shapes.length === 0 || shapes.some((shape) => !shape.d)) {
    throw new Error(`${name}: no path geometry found`)
  }
  return shapes
}

const names = JSON.parse(readFileSync(namesFile, 'utf8'))
if (new Set(names).size !== names.length) throw new Error('phosphor-names.json has a duplicate')

const glyphs = Object.fromEntries(
  [...names]
    .sort()
    .map((name) => [name, {style: 'fill', viewBox: '0 0 256 256', shapes: readShapes(name)}]),
)

const source = `// Generated by scripts/generate-phosphor-icons.mjs from phosphor-names.json. Do not edit.
export const PHOSPHOR_GLYPHS = ${JSON.stringify(glyphs)} as const

export type PhosphorIconName = keyof typeof PHOSPHOR_GLYPHS
`

const options = (await resolveConfig(outputFile)) ?? {}
writeFileSync(outputFile, await format(source, {...options, filepath: outputFile}))
