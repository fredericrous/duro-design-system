/**
 * The generated Claude Code hooks — SessionStart (catalog) and UserPromptSubmit
 * (plan-mode nudge) — and the wiring they need.
 *
 * Kept as data (not prose in a README) so `duro hook install` can write it and
 * `duro hook install --check` can byte-compare it: every consuming repo runs
 * the same script, and an upgrade is a regenerate rather than nine hand-edits.
 */

/** Repo-relative paths the hook owns. */
export const HOOK_SCRIPT_PATH = '.claude/hooks/duro-catalog.sh'
export const HOOK_SETTINGS_PATH = '.claude/settings.json'
export const HOOK_CACHE_PATH = '.claude/.duro-session.cache'
/**
 * `duro doctor --session` output, and the key of the files it was computed
 * from. Named under HOOK_CACHE_PATH so the existing ignore glob covers them —
 * no .gitignore drift in the repos already wired.
 */
export const HOOK_DOCTOR_CACHE_PATH = `${HOOK_CACHE_PATH}.doctor`
/**
 * Glob, not the bare path: the script stages the fetch through
 * "<cache>.tmp", and a session-start hook killed mid-npx leaves that behind.
 */
export const HOOK_CACHE_IGNORE = `${HOOK_CACHE_PATH}*`
/** Repo-specific caveats, appended by the hook and never touched by install. */
export const HOOK_NOTES_PATH = '.claude/duro-hook.local.md'

/** What settings.json runs. Also the marker install matches on. */
export const HOOK_COMMAND = `sh ${HOOK_SCRIPT_PATH}`

/**
 * Floor for the npx pin. Raise this only when the session payload needs
 * newer CLI behavior — a floating pin keeps patch releases from showing up
 * as --check drift, but a floor left behind a major means no consumer ever
 * sees what the payload gained (1.2.0 pinned every repo out of 2.x).
 * 3.0.0: the SCREENS section and the /duro-mockup pointer.
 * 3.4.0: duro doctor --session.
 * 4.4.0: the first CLI whose payload matches @duro-app/ui 4 — a ^3 floor
 *        never reaches 4.x, so 4.x consumers were served 3.x docs. The
 *        release refuses a tag whose major differs from this floor's
 *        (scripts/check-pin-major.mjs).
 */
export const HOOK_MIN_CLI = '4.4.0'

/**
 * First line of the catalog cache: the floor it was fetched with. A cache
 * from another floor is refetched, and this line is never printed.
 */
export const HOOK_PIN_LINE = `#duro-hook-pin ${HOOK_MIN_CLI}`

export const HOOK_SCRIPT = `#!/bin/sh
# Duro design-system session bootstrap — GENERATED by \`duro hook install\`.
# Regenerate: npx -y @duro-app/cli hook install   (--check verifies it in CI)
#
# Injects the consult-first preamble plus the component catalog into agent
# context at SessionStart, so "check the design system before building UI" is
# ambient context instead of a step an agent has to remember. Then runs
# \`duro doctor\`, which says nothing unless this repo's build wiring flattens
# the components' styles.
#
# Do not hand-edit. Repo-specific caveats go in
# ${HOOK_NOTES_PATH} — appended below, and left alone by regeneration.
cache="${HOOK_CACHE_PATH}"
notes="${HOOK_NOTES_PATH}"
doctor="${HOOK_DOCTOR_CACHE_PATH}"
pin="${HOOK_PIN_LINE}"

# npx resolution dominates session start; the catalog only changes on upgrade.
# Refetch when it is missing, a week old, fetched with another floor (its
# first line), or older than this script (a regenerate).
if [ ! -s "$cache" ] || [ "$(head -n 1 "$cache" 2>/dev/null)" != "$pin" ] ||
  [ -n "$(find "$cache" -mtime +7 2>/dev/null)" ] || [ "${HOOK_SCRIPT_PATH}" -nt "$cache" ]; then
  # The pin is written with the payload, so a failed fetch leaves the old
  # cache as it was and never a pin-only file.
  if { echo "$pin"; npx -y @duro-app/cli@^${HOOK_MIN_CLI} hook session-start; } >"$cache.tmp" 2>/dev/null; then
    mv "$cache.tmp" "$cache"
  else
    rm -f "$cache.tmp"
    if [ -s "$cache" ] && [ "$(head -n 1 "$cache")" != "$pin" ]; then
      echo "duro: the catalog below is from an older CLI and could not be refreshed; run: npx -y @duro-app/cli@^${HOOK_MIN_CLI} hook install" >&2
    fi
  fi
fi

# Offline with no cache yet: stay silent rather than fail the session.
if [ -s "$cache" ]; then
  # The pin line is bookkeeping, not catalog: skip it, and only it.
  case "$(head -n 1 "$cache")" in
    '#duro-hook-pin '*) tail -n +2 "$cache" ;;
    *) cat "$cache" ;;
  esac
  if [ -s "$notes" ]; then
    echo
    cat "$notes"
  fi
fi

# duro doctor reads build config, entries and stylesheets. Re-run it when one
# of those changes rather than on a timer, so an edit shows up next session
# and a healthy repo only pays for npx after touching its config.
key=$(find . -maxdepth 4 \\( -name node_modules -o -name .git -o -name dist -o -name build \\) -prune -o \\
  -type f \\( -name package.json -o -name pnpm-workspace.yaml -o -name '*.css' -o -name 'vite*' \\
  -o -name 'babel*' -o -name '.babelrc*' -o -name '*.babel.*' -o -name 'postcss*' \\
  -o -name 'root.tsx' -o -name 'main.tsx' -o -name 'index.tsx' \\) -exec cksum {} + 2>/dev/null |
  sort | cksum)
# The floor is part of the key: a new floor reruns the doctor.
key="${HOOK_MIN_CLI} $key"
if [ "$key" != "$(cat "$doctor.key" 2>/dev/null)" ]; then
  if npx -y @duro-app/cli@^${HOOK_MIN_CLI} doctor --session >"$doctor.tmp" 2>/dev/null; then
    mv "$doctor.tmp" "$doctor"
    echo "$key" >"$doctor.key"
  else
    rm -f "$doctor.tmp"
  fi
fi
if [ -s "$doctor" ]; then
  echo
  cat "$doctor"
fi
`

/**
 * The UserPromptSubmit hook: a plan-mode nudge toward fresh mockup
 * directions (fleet decision `handoff.fresh-directions-trigger`), so a plan
 * that adds a screen or makes a material UI choice puts the direction pick
 * first without anyone typing /duro-mockup.
 */
export const PLAN_HOOK_SCRIPT_PATH = '.claude/hooks/duro-plan.sh'

/** What settings.json runs on UserPromptSubmit. Also the marker install matches on. */
export const PLAN_HOOK_COMMAND = `sh ${PLAN_HOOK_SCRIPT_PATH}`

/** Printed into the planner's context, and only while in plan mode. */
export const PLAN_NUDGE = `Planning in a Duro consumer. If this plan adds a new screen, or makes a material choice in
layout, hierarchy or interaction (handoff.fresh-directions-trigger), its first 🧑 decision is
picking a direction: load the duro-mockup skill now (duro skill install if this repo lacks it)
and draw 2–4 directions with \`duro mockup\` before ExitPlanMode. A fix that restores an existing
design reuses the picked artboard instead; any other UI change needs no mockup.
`

/**
 * Runs on every prompt, so it is pure sh with one grep: no npx, no node, no
 * network. Claude Code sends the event as one JSON object on stdin, and
 * stdout of a UserPromptSubmit hook that exits 0 joins the model's context.
 * Every path exits 0 — exit 2 would block the prompt. The whole payload is
 * read before grep runs, so an early grep exit never breaks Claude Code's
 * write. A `"permission_mode":"plan"` typed inside the prompt arrives
 * escaped (\"permission_mode\"), which the pattern does not match.
 */
export const PLAN_HOOK_SCRIPT = `#!/bin/sh
# Duro plan-mode nudge — GENERATED by \`duro hook install\`.
# Regenerate: npx -y @duro-app/cli hook install   (--check verifies it in CI)
#
# Claude Code runs this on every UserPromptSubmit with the event as JSON on
# stdin. In plan mode it prints a short nudge toward fresh mockup directions
# (handoff.fresh-directions-trigger); otherwise, or on input it cannot read,
# it prints nothing. Always exits 0: it must never fail the prompt.
#
# Do not hand-edit.
{ payload=$(cat); } 2>/dev/null || exit 0
if printf '%s\\n' "$payload" |
  grep -Eq '"permission_mode"[[:space:]]*:[[:space:]]*"plan"' 2>/dev/null; then
  cat <<'NUDGE'
${PLAN_NUDGE}NUDGE
fi
exit 0
`

export const GITIGNORE_BLOCK = `# Duro session-hook cache (duro hook install)\n${HOOK_CACHE_IGNORE}\n`
